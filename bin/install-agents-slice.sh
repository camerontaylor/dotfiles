#!/usr/bin/env bash
# install-agents-slice.sh — Generate persistent ~/.config/systemd/user/agents.slice
# with MemoryMax = host_ram - 6G, then enable + start it.
#
# Run once per host. Re-run after RAM changes.
# Source of truth lives in dotfiles; the slice file in ~/.config/ is generated.
#
# Background: replaces the broken resmon-cglauncher's transient slice setup.
# The slice is the umbrella for every interactive shell + every worktree scope.
# Memory not in this slice (~6G) is implicitly reserved for UI/system (Ghostty,
# GNOME, browser, IDE). See .omc/specs/deep-interview-cgroup-management-overhaul.md.

set -euo pipefail

# Defensive: systemd --user requires XDG_RUNTIME_DIR. In some shells (cron, sshd
# without PAM systemd integration, certain TTYs) it may be unset.
export XDG_RUNTIME_DIR="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"

# Confirm systemd --user is reachable. If not, fail loudly with a hint.
if ! systemctl --user is-system-running >/dev/null 2>&1 \
   && ! systemctl --user list-units >/dev/null 2>&1; then
  echo "ERROR: systemd --user is not running. Are you in a graphical session," >&2
  echo "       or did 'systemctl --user' get reset? See loginctl enable-linger \$USER." >&2
  exit 1
fi

HEADROOM_BYTES=$((6 * 1024 * 1024 * 1024))  # 6G (was 7G in cglauncher:19; standardized
                                            # down per spec line 34. Slightly tighter
                                            # UI headroom; justified because cap is
                                            # now per-host computed from RAM.)
TOTAL_RAM_KB=$(awk '/^MemTotal:/ { print $2 }' /proc/meminfo)
TOTAL_RAM_BYTES=$(( TOTAL_RAM_KB * 1024 ))

if (( TOTAL_RAM_BYTES <= HEADROOM_BYTES )); then
  echo "ERROR: total RAM <= 6G headroom; refusing to compute negative MemoryMax" >&2
  exit 1
fi

CAP_BYTES=$(( TOTAL_RAM_BYTES - HEADROOM_BYTES ))

# Sanity bound (upper): cap must be < 90% of total RAM. Defends against accidentally
# setting HEADROOM_BYTES too small (e.g., a typo of 6*1024 instead of 6*1024^3).
NINETY_PCT=$(( TOTAL_RAM_BYTES * 90 / 100 ))
if (( CAP_BYTES >= NINETY_PCT )); then
  echo "ERROR: computed cap ($CAP_BYTES) >= 90% of total RAM ($TOTAL_RAM_BYTES)." >&2
  echo "       HEADROOM_BYTES is too small; refusing to write unit file." >&2
  exit 1
fi

# Sanity bound (lower): refuse impossibly small caps (would brick the system).
if (( CAP_BYTES < 4 * 1024 * 1024 * 1024 )); then
  echo "ERROR: computed cap ($CAP_BYTES) < 4G. Host is too small for this design." >&2
  exit 1
fi

UNIT_DIR="$HOME/.config/systemd/user"
UNIT_FILE="$UNIT_DIR/agents.slice"
mkdir -p "$UNIT_DIR"

cat > "$UNIT_FILE" <<EOF
[Unit]
Description=All-the-dev-stuff-via-terminal slice (agents + worktree scopes)
DefaultDependencies=no
Before=shutdown.target
# Generated by ~/.local/dotfiles/bin/install-agents-slice.sh
# Cap = total RAM ($TOTAL_RAM_BYTES bytes) - 6G headroom = $CAP_BYTES bytes
# Re-run the installer after changing host RAM.

[Slice]
MemoryAccounting=yes
MemoryMax=${CAP_BYTES}
MemorySwapMax=0

[Install]
WantedBy=default.target
EOF

systemctl --user daemon-reload
systemctl --user enable agents.slice    # creates default.target.wants/agents.slice symlink
systemctl --user start agents.slice     # activates the running instance now

# Verification echo
echo "Computed MemoryMax: $CAP_BYTES bytes ($(numfmt --to=iec "$CAP_BYTES" 2>/dev/null || echo '?'))"
echo "is-enabled: $(systemctl --user is-enabled agents.slice)"
echo "is-active:  $(systemctl --user is-active agents.slice)"
